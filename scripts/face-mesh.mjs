#!/usr/bin/env node
// Writes src/hud/face-mesh.ts, the face the HUD draws, from a baked face:
// the front of a head from the Momentum Human Rig at its mean identity (no
// one's face) as points, wire edges, unit normals, the region each point
// belongs to and one displacement per expression channel, and a table of
// per-channel drawing gains. See LICENSE-MHR.
//
//   node scripts/face-mesh.mjs <baked-face.json> <gains.json>

import { readFileSync, writeFileSync } from 'node:fs';

const [facePath, gainsPath] = process.argv.slice(2);
if (!facePath || !gainsPath) {
  console.error('usage: node scripts/face-mesh.mjs <baked-face.json> <gains.json>');
  process.exit(2);
}
const face = JSON.parse(readFileSync(facePath, 'utf8'));
const gains = JSON.parse(readFileSync(gainsPath, 'utf8')).gains;

const CHANNELS = [
  'eyeBlinkL', 'eyeBlinkR', 'eyeWideL', 'eyeWideR', 'browDownL', 'browDownR', 'browInnerUp', 'browOuterUpL', 'browOuterUpR', 'jawOpen', 'lipsPart', 'mouthSmileL',
  'mouthSmileR', 'mouthStretch', 'mouthPucker', 'noseSneer', 'noseFlare', 'cheekSquintL', 'cheekSquintR', 'chinRaise', 'lidTighten', 'browTogether', 'noseWrinkle', 'lidRaise',
];
for (const name of CHANNELS) {
  if (!face.deltas[name]) throw new Error(`the baked face has no displacement for ${name}`);
  if (typeof gains[name] !== 'number') throw new Error(`no gain for ${name}`);
}
if ((face.deltaDims ?? 2) !== 3) throw new Error('displacements must have three dimensions');

const mesh = {
  count: face.count,
  headHeight: face.frame.headHeight,
  pivot: face.frame.pivot,
  points: face.points,
  edges: face.edges,
  regions: face.regions,
  region: face.region,
  weight: face.weight,
  normals: face.normals,
  gains: Object.fromEntries(CHANNELS.map((name) => [name, gains[name]])),
  deltas: Object.fromEntries(CHANNELS.map((name) => [name, { idx: face.deltas[name].idx, d: face.deltas[name].d }])),
};

const header = `// Generated by scripts/face-mesh.mjs; do not edit.
//
// The face the HUD draws: the front of a head from the Momentum Human Rig
// v1.0.1 at its mean identity and rest pose, which is no one's face.
// Copyright (c) Meta Platforms, Inc. and affiliates, licensed under the
// Apache License 2.0 (LICENSE-MHR at the package's root).
//
// Frame: x to the viewer's right (the person's own left at the viewer's
// left), y down, z toward the viewer; the head ${mesh.headHeight} units tall.
// Per point: x, y, z; its unit normal x 100; the region it belongs to
// (\`regions\`, or -1); how much of the region's motion it carries, 0 to
// 100. Per channel: the points it moves and their dx, dy, dz at full scale,
// and the gain a full reading is drawn at.

import type { FaceMesh } from './face.ts';

`;
writeFileSync(new URL('../src/hud/face-mesh.ts', import.meta.url), `${header}export const FACE_MESH: FaceMesh = ${JSON.stringify(mesh)};\n`);
console.log(`wrote src/hud/face-mesh.ts: ${mesh.count} points, ${mesh.edges.length / 2} edges, ${CHANNELS.length} channels`);
